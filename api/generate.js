import { authenticateRequest } from './_utils/auth.js';

export default async function handler(req, res) {
  res.setHeader('Access-Control-Allow-Origin', '*');
  res.setHeader('Access-Control-Allow-Methods', 'POST, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type, Authorization');

  if (req.method === 'OPTIONS') return res.status(200).end();
  if (req.method !== 'POST') return res.status(405).json({ error: 'Method not allowed' });

  // JWT 인증 체크 (전환기: 토큰 없어도 허용, 로그만 남김)
  const authUser = authenticateRequest(req);
  if (!authUser) {
    console.warn('generate.js: 인증되지 않은 요청');
  }

  const { activity, needAction, model, tone, charCount, includeExpertView } = req.body;
  if (!activity) return res.status(400).json({ error: '활동내용을 입력해주세요.' });

  const MODEL_MAP = {
    'haiku': 'claude-haiku-4-5-20251001',
    'sonnet': 'claude-sonnet-4-6'
  };
  const selectedModel = MODEL_MAP[model] || MODEL_MAP['haiku'];

  // 글자 수 설정
  const charCountText = charCount ? `${charCount}자 내외` : '140자 내외';

  // 말투별 프롬프트 블록
  const TONE_MAP = {
    'default': {
      name: '기본',
      structure: `   - 시작: "[활동명]을(를) ~하는 시간을 가졌습니다" (※ '오늘'로 시작하지 마세요)
   - 중간: 이용자의 행동과 발화를 시간 순서대로 서술
   - 끝맺음: 마지막 행동 뒤에 "~며" + 전문적 견해 + "나타냈습니다/보였습니다"`,
      style: `   - 정형적이고 체계적인 문장 구조를 사용합니다
   - 접속사 "~하고", "~하며"를 활용하여 매끄럽게 연결합니다
   - 객관적이고 균형 잡힌 톤을 유지합니다
   - ❌ 이 말투에서는 직접 인용("..."이라고 말함)을 쓰지 마세요
   - ❌ 분위기 부사(살며시, 환하게, 조심스럽게 등)를 쓰지 마세요`,
      example: `"비빔국수 요리수업을 하는 시간을 가졌습니다. 이용자는 재료를 직접 썰고 양념장을 만드는 과정에 적극적으로 참여했습니다. 완성된 국수를 바라보며 뿌듯한 표정을 짓고 활동에 대한 성취감을 표현했습니다."`
    },
    'warm': {
      name: '따뜻한 공감형',
      structure: `   - 시작: "[활동명]을(를) 함께 해보는 시간이었습니다" 또는 "[활동명]을(를) 하며 의미 있는 시간을 보냈습니다" (※ '오늘'로 시작하지 마세요, 기본형의 "시간을 가졌습니다"를 쓰지 마세요)
   - 중간: 이용자의 표정, 눈빛, 목소리 톤, 분위기 변화를 세심하게 포착하여 서술
   - 끝맺음: 이용자의 작은 변화나 성장을 따뜻하게 마무리`,
      style: `   - "살며시", "환하게", "편안한 모습으로", "조심스럽게", "즐거운 표정으로", "차분하게" 등 분위기를 전달하는 부사와 형용사를 반드시 2개 이상 사용합니다
   - 이용자의 표정과 분위기 변화(처음→중간→끝)의 흐름을 서술합니다
   - 작은 변화나 성장에 주목하는 시선으로 씁니다
   - ❌ 직접 인용("..."이라고 말함)은 쓰지 마세요 (생동감형과 구분)
   - ❌ 딱딱한 보고서 톤("참여했습니다", "진행했습니다")을 피하세요`,
      example: `"비빔국수 요리수업을 함께 해보는 시간이었습니다. 이용자는 재료를 하나씩 살펴보며 조심스럽게 썰기 시작했습니다. 양념장을 만드는 동안 점차 편안한 표정으로 활동에 몰입했으며, 완성된 국수를 바라보며 환하게 미소 짓는 모습이었습니다."`
    },
    'concise': {
      name: '담백한 요약형',
      structure: `   - 시작: "[활동명]에 참여했습니다" (※ '오늘'로 시작하지 마세요, 짧게 시작)
   - 중간: 핵심 행동만 짧은 문장으로 나열
   - 끝맺음: 결과나 반응 한 문장으로 마무리`,
      style: `   - 한 문장에 하나의 행동만 씁니다
   - 꾸밈말, 수식어, 분위기 부사를 쓰지 않습니다
   - 접속사("~하고", "~하며") 대신 마침표로 문장을 끊습니다
   - 전체 3~4문장 이내로 마칩니다
   - ❌ "적극적으로", "열심히" 등 평가성 부사를 쓰지 마세요
   - ❌ 분위기 묘사, 직접 인용을 쓰지 마세요`,
      example: `"비빔국수 요리수업에 참여했습니다. 이용자는 재료를 직접 썰고 양념장을 만들었습니다. 완성된 국수를 보며 뿌듯한 표정을 지었습니다."`
    },
    'vivid': {
      name: '생동감 있는 서술형',
      structure: `   - 시작: 바로 활동 장면으로 들어갑니다. "[활동명] 활동이 시작되자" 또는 "[활동 재료/도구]를 앞에 놓고" 등 (※ '오늘'로 시작하지 마세요, "시간을 가졌습니다"를 쓰지 마세요)
   - 중간: 이용자의 구체적 동작과 발화를 시간 순서로 생생하게 묘사
   - 끝맺음: 이용자의 인상적인 발화나 행동 장면으로 자연스럽게 마무리`,
      style: `   - 이용자의 말을 반드시 직접 인용합니다 ("내가 만들었다!", "이거 해볼래요" 등)
   - 구체적 동작을 묘사합니다 (손을 뻗다, 고개를 갸웃거리다, 몸을 앞으로 기울이다 등)
   - "~하다가", "~하자", "~한 뒤" 등 동적인 접속 표현으로 장면을 이어갑니다
   - 읽는 사람이 그 장면을 머릿속에 그릴 수 있도록 서술합니다
   - ❌ "시간을 가졌습니다", "참여했습니다" 등 정형적 표현을 쓰지 마세요
   - ❌ 분위기 부사(살며시, 환하게 등)보다 동작 묘사에 집중하세요`,
      example: `"비빔국수 재료가 놓이자 이용자는 바로 칼을 집어 들고 야채를 썰기 시작했습니다. 양념장 재료를 하나씩 넣어가며 맛을 보다가, 완성된 국수를 앞에 놓고 \"내가 만들었다!\"라고 말하며 뿌듯한 표정을 지었습니다."`
    }
  };

  const toneConfig = TONE_MAP[tone] || TONE_MAP['default'];

  // 전문적 견해 블록
  const expertViewBlock = includeExpertView !== false
    ? `\n5. **전문적 견해 패턴** (끝맺음에 자연스럽게 녹여서 작성)
   긍정적: "활동에 대한 즐거움과 성취감을 표현했습니다", "높은 몰입도와 집중력을 나타냈습니다"
   부정적: "지속적인 집중력 유지에 어려움을 보였습니다"`
    : `\n5. **전문적 견해 제외**
   - 전문적 평가나 분석적 견해를 넣지 마세요
   - 관찰한 행동과 사실만 서술하세요
   - "~을 나타냈습니다", "~을 표현했습니다" 같은 평가성 표현을 쓰지 마세요`;

  const prompt = `당신은 성인 발달장애인 주간활동센터 '감사합니다'의 사회복지사입니다. 아래 구어체 활동 내용을 전문적인 관찰일지로 작성해주세요.

**작성 규칙:**

1. **기본 구조**
${toneConfig.structure}

2. **중요: '이용자는' 표현 규칙**
   - "이용자는 ~했습니다" 형태는 글 전체에서 딱 한 번만 사용
   - 이후 문장에서는 "이용자는"을 생략하고 바로 행동을 서술

3. **문체 규칙 (${toneConfig.name})**
${toneConfig.style}
   - 참고 예시: ${toneConfig.example}

4. **호칭 규칙**
   - 직원, 선생님, 제공인력 등은 모두 "관찰자"로 통일
   - 단, "강사", "강사님"은 그대로 유지 (관찰자로 바꾸지 마세요)
${expertViewBlock}

6. **⚠️ 사실 충실 원칙 (매우 중요)**
   - 입력 내용의 사실 관계를 절대 뒤집지 마세요
     예) 입력이 "잘 모름" → "점차 이해해 나갔습니다" ❌ (사실 왜곡)
     예) 입력이 "잘 모름" → "어려움을 보였습니다" ✅ (사실 유지)
   - 입력에 없는 새로운 행동(활동 중단, 고개 끄덕임 등)을 만들지 마세요
   - 입력이 짧을 경우, 동일한 상황의 세부 묘사(표정, 자세, 동작)로 보충하되 새로운 사건을 만들지 마세요

7. **⚠️ 객관적 표현 원칙 (매우 중요)**
   - 감정을 직접 서술하지 말고, 관찰 가능한 행동이나 표정으로 표현하세요
     "즐거워했습니다" ❌ → "즐거운 표정을 보였습니다" ✅
     "뿌듯함을 느꼈습니다" ❌ → "뿌듯한 표정을 지었습니다" ✅
     "어색해했습니다" ❌ → "어색한 모습을 보였습니다" ✅
     "인상적이었습니다" ❌ → (관찰자 주관이므로 삭제) ✅
   - "~을 느꼈습니다", "~해했습니다" 대신 "~한 표정/모습/반응을 보였습니다"로 바꾸세요
   - ⚠️ 문장 끝 표현의 다양성: "~나타냈습니다"와 "~보였습니다"를 골고루 섞어서 사용하세요. 한쪽 표현만 반복하지 마세요.
     활용 가능한 끝맺음: "~을 보였습니다", "~을 나타냈습니다", "~한 모습이었습니다", "~한 표정을 지었습니다", "~하는 반응을 보였습니다"

8. **⚠️ 처방/판단 금지**
   - "~이 필요합니다", "~해야 합니다" 같은 처방적 표현을 쓰지 마세요
   - "~인 것으로 보입니다" 같은 추측 판단을 쓰지 마세요
   - 관찰한 사실만 기록하고, 해결방안이나 진단은 넣지 마세요

9. **구어체 → 격식체 변환**
   - 했어 → 했습니다
   - 보였어 → 보였습니다
   - 말했어 → 말했습니다
   - 반드시 경어체(~했습니다, ~보였습니다)를 사용하세요. 줄임말이나 반말체는 절대 사용하지 마세요.

10. **처리사항 생성 규칙**
   ${needAction ? '- 처리사항을 반드시 포함해서 작성해주세요.\n   - 처리사항은 50자 내외로 작성\n   - "~안내해드렸습니다", "~도와드렸습니다", "~격려했습니다" 형태 사용' : '- 처리사항을 절대 포함하지 마세요.\n   - 관찰일지 내용만 작성하세요.\n   - [처리사항] 태그를 사용하지 마세요.'}

11. **글자 수**
   - 관찰일지: ${charCountText}

12. **출력 형식**
   ${needAction ? '- [관찰일지]\n   (관찰 내용)\n   \n   [처리사항]\n   (처리사항 내용)' : '- 관찰일지 내용만 출력하세요.\n   - [관찰일지] 태그도 사용하지 마세요.\n   - 바로 내용만 작성하세요.'}

**입력된 활동 내용:**
${activity}

위 내용을 규칙에 맞게 관찰일지로 작성해주세요. 다른 설명 없이 요청된 형식대로만 출력하세요.`;

  try {
    const response = await fetch("https://api.anthropic.com/v1/messages", {
      method: "POST",
      headers: {
        "Content-Type": "application/json",
        "x-api-key": process.env.ANTHROPIC_API_KEY,
        "anthropic-version": "2023-06-01"
      },
      body: JSON.stringify({
        model: selectedModel,
        max_tokens: 1000,
        messages: [{ role: "user", content: prompt }]
      })
    });
    const data = await response.json();
    if (data.error) return res.status(500).json({ error: data.error.message });
    return res.status(200).json({ result: data.content?.[0]?.text?.trim() || '' });
  } catch (error) {
    return res.status(500).json({ error: '서버 오류: ' + error.message });
  }
}
